class RegistrationSession {
  String? username;
  String? identifier;
  String? password;
  String? fullName;     
  String? studentId;
  String? schoolId;
  String? userId;

  void clear() {
    username = null;
    identifier = null;
    password = null;
    fullName = null;
    studentId = null;
    schoolId = null;
    userId = null;
  }
}